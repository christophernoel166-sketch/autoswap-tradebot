import { createNotification } from "./notificationService.js";
import User from "../../models/User.js";
import {
  enqueueTelegramNotification,
} from "./telegramQueueService.js";

import SignalChannel from "../../models/SignalChannel.js";

const SYSTEM_CHANNEL_ID =
  process.env.SYSTEM_TELEGRAM_CHANNEL_ID;


function generateNotificationId() {
  return `NTF-${Date.now()}-${Math.random()
    .toString(36)
    .slice(2, 8)
    .toUpperCase()}`;
}



// =====================================================
// BUILD NOTIFICATION
// =====================================================

function buildNotification(result, watch) {
  switch (result.event) {
    case "BREAKOUT_CONFIRMED":
      return {
        type: "success",
        title: "🚀 Breakout Confirmed",
        message: `${watch.symbol || "Token"} has confirmed its breakout. Entry conditions have been met.`,
      };

    case "PULLBACK_COMPLETED":
      return {
        type: "success",
        title: "📈 Pullback Complete",
        message: `${watch.symbol || "Token"} has completed its pullback and is ready for entry.`,
      };

    case "SETUP_INVALIDATED":
      return {
        type: "warning",
        title: "❌ Setup Invalidated",
        message: `${watch.symbol || "Token"} is no longer a valid trade setup.`,
      };

    case "BREAKOUT_FAILED":
      return {
        type: "warning",
        title: "⚠️ Breakout Failed",
        message: `${watch.symbol || "Token"} failed to confirm its breakout.`,
      };

    case "PULLBACK_FAILED":
      return {
        type: "warning",
        title: "⚠️ Pullback Failed",
        message: `${watch.symbol || "Token"} failed to complete its pullback.`,
      };

    default:
      return null;
  }
}

// =====================================================
// BUILD TELEGRAM CHANNEL MESSAGE
// =====================================================

function buildTelegramChannelMessage(
  watch,
  result,
  payload,
  notificationId
) {
  return `
${payload.title}

🆔 <b>Notification ID:</b> <code>${notificationId}</code>

🪙 <b>Token:</b> ${watch.symbol || "Unknown"}

📍 <b>Contract:</b> <code>${watch.mintAddress || "Unknown"}</code>

📊 <b>Event:</b> ${result.event}

⏮ <b>Previous:</b> ${result.previousAction ?? "-"}

▶️ <b>Current:</b> ${result.currentAction ?? "-"}

${payload.message}

🤖 <i>Generated by Autoswaps AI Chart Monitor</i>
`;
}

// =====================================================
// NOTIFY CHART WATCH
// =====================================================

export async function notifyChartWatch(watch, result) {
  if (!watch || !result) return;

const payload = buildNotification(result, watch);
if (!payload) return;

const notificationId = generateNotificationId();

console.log("🆔 Chart notification created:", {
  notificationId,
  watchId: watch._id,
  symbol: watch.symbol,
  event: result.event,
  watchType: watch.watchType,
});

  // ===================================================
  // SYSTEM WATCH
  // ===================================================

  if (watch.watchType === "SYSTEM") {

const ENTRY_EVENTS = new Set([
  "BREAKOUT_CONFIRMED",
  "PULLBACK_COMPLETED",
]);

if (!ENTRY_EVENTS.has(result.event)) {
  return;
}

    if (!SYSTEM_CHANNEL_ID) {
      console.error(
        "❌ SYSTEM CHART NOTIFICATION — SYSTEM_TELEGRAM_CHANNEL_ID is missing"
      );
      return;
    }
  

    // -----------------------------------------------
    // DASHBOARD — APPROVED SUBSCRIBERS
    // -----------------------------------------------

    const users = await User.find({
      subscribedChannels: {
        $elemMatch: {
          channelId: SYSTEM_CHANNEL_ID,
          enabled: true,
          status: "approved",
        },
      },
    })
      .select("walletAddress")
      .lean();

    console.log(
      "📢 SYSTEM CHART NOTIFICATION — subscribers",
      {
        channelId: SYSTEM_CHANNEL_ID,
        subscriberCount: users.length,
        watchId: watch._id,
        symbol: watch.symbol,
        event: result.event,
      }
    );

    for (const user of users) {
      if (!user.walletAddress) continue;

      await createNotification({
        walletAddress: user.walletAddress,
        type: payload.type,
        title: payload.title,
        message: payload.message,
        data: {
          watchId: watch._id,
          tokenMint: watch.mintAddress,
          tokenSymbol: watch.symbol,
          previousAction: result.previousAction,
          currentAction: result.currentAction,
          event: result.event,
          channelId: SYSTEM_CHANNEL_ID,
        },
      });
    }

    // -----------------------------------------------
    // TELEGRAM CHANNEL
    // -----------------------------------------------

    try {
      const telegramMessage =
  buildTelegramChannelMessage(
    watch,
    result,
    payload,
    notificationId
  );

      await enqueueTelegramNotification({
        telegramChannelId: SYSTEM_CHANNEL_ID,
        message: telegramMessage,
        parseMode: "HTML",
      });

      console.log(
  "📨 SYSTEM CHART NOTIFICATION — Telegram channel queued",
  {
    notificationId,
    channelId: SYSTEM_CHANNEL_ID,
    watchId: watch._id,
    symbol: watch.symbol,
    event: result.event,
  }
);
    } catch (telegramError) {
      console.error(
        "❌ SYSTEM CHART NOTIFICATION — Telegram channel queue failed:",
        telegramError?.message || telegramError
      );
    }

    return;
  }


  // ===================================================
  // USER WATCH
  // ===================================================

  if (!watch.walletAddress) {
    console.warn(
      "⚠️ USER CHART NOTIFICATION — missing walletAddress",
      {
        watchId: watch._id,
        symbol: watch.symbol,
        event: result.event,
      }
    );

    return;
  }

  // -----------------------------------------------
  // DASHBOARD — preserve existing behavior
  // -----------------------------------------------

  await createNotification({
    walletAddress: watch.walletAddress,
    type: payload.type,
    title: payload.title,
    message: payload.message,
    data: {
      watchId: watch._id,
      tokenMint: watch.mintAddress,
      tokenSymbol: watch.symbol,
      previousAction: result.previousAction,
      currentAction: result.currentAction,
      event: result.event,
    },
  });

  // -----------------------------------------------
  // TELEGRAM — only this user's claimed channel
  // -----------------------------------------------

  const ENTRY_EVENTS = new Set([
    "BREAKOUT_CONFIRMED",
    "PULLBACK_COMPLETED",
  ]);

  if (!ENTRY_EVENTS.has(result.event)) {
    return;
  }

  try {
    const channel = await SignalChannel.findOne({
      ownerWallet: watch.walletAddress,
      status: "active",
    }).lean();

    if (!channel?.channelId) {
      console.warn(
        "⚠️ USER CHART NOTIFICATION — no active owned channel found",
        {
          watchId: watch._id,
          walletAddress: watch.walletAddress,
          event: result.event,
        }
      );

      return;
    }

    const telegramMessage = buildTelegramChannelMessage(
      watch,
      result,
      payload,
      notificationId
    );

    await enqueueTelegramNotification({
      notificationId,
      telegramChannelId: channel.channelId,
      message: telegramMessage,
      parseMode: "HTML",
    });

    console.log(
      "📨 USER CHART NOTIFICATION — Telegram channel queued",
      {
        notificationId,
        channelId: channel.channelId,
        watchId: watch._id,
        symbol: watch.symbol,
        event: result.event,
      }
    );
  } catch (telegramError) {
    console.error(
      "❌ USER CHART NOTIFICATION — Telegram channel queue failed:",
      telegramError?.message || telegramError
    );
  }
}
